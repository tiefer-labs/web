// Writes src/components/home/globe-data.ts: run `node scripts/globe-data.ts` after changing GLOBE.
import { writeFileSync } from "node:fs";
import { geoContains, geoOrthographic, geoPath } from "d3-geo";
import { feature } from "topojson-client";
import type { GeometryCollection, Topology } from "topojson-specification";
import land50m from "world-atlas/land-50m.json" with { type: "json" };
import land110m from "world-atlas/land-110m.json" with { type: "json" };
import { GLOBE, project } from "../src/components/home/globe.ts";

const VIEW = { left: 420, right: 1450, top: 90, bottom: 770 };
const STEP = 0.55;

// oxlint-disable-next-line typescript/no-unsafe-type-assertion
const topology = land50m as unknown as Topology<{ land: GeometryCollection }>;
const land = feature(topology, topology.objects.land);
// oxlint-disable-next-line typescript/no-unsafe-type-assertion
const coarse = land110m as unknown as Topology<{ land: GeometryCollection }>;
const inView = (p: { x: number; y: number; front: boolean }) =>
  p.front && p.x >= VIEW.left && p.x <= VIEW.right && p.y >= VIEW.top && p.y <= VIEW.bottom;

// Equal-area grid: fewer longitude steps towards the pole, so dots stay evenly spaced on the ground.
const dots: string[] = [];
// Every place in the view, so the dots cover all the land the coastline outlines.
for (let lat = 0; lat <= 86; lat += STEP) {
  const lonStep = STEP / Math.cos((lat * Math.PI) / 180);
  for (let lon = -110; lon <= 150; lon += lonStep) {
    const p = project(lon, lat);
    if (inView(p) && geoContains(land, [lon, lat])) dots.push(`M${Math.round(p.x)} ${Math.round(p.y)}h0`);
  }
}

// Every 10 degrees, sampled each degree, broken where a line leaves the view.
function polyline(points: { x: number; y: number; front: boolean }[]) {
  let d = "";
  let pen = false;
  for (const p of points) {
    if (!inView(p)) {
      pen = false;
      continue;
    }
    d += `${pen ? "L" : "M"}${Math.round(p.x)} ${Math.round(p.y)}`;
    pen = true;
  }
  return d;
}
const range = (from: number, to: number, step: number) =>
  Array.from({ length: Math.floor((to - from) / step) + 1 }, (_, i) => from + i * step);
const graticule = [
  ...range(-110, 150, 10).map((lon) => polyline(range(0, 85, 1).map((lat) => project(lon, lat)))),
  ...range(10, 80, 10).map((lat) => polyline(range(-120, 160, 1).map((lon) => project(lon, lat)))),
].join("");

// The same view as project(), clipped to the box, for the coastline.
const projection = geoOrthographic()
  .rotate([GLOBE.lambda, GLOBE.phi])
  .scale(GLOBE.radius)
  .translate([GLOBE.x, GLOBE.y])
  .clipExtent([
    [VIEW.left, VIEW.top],
    [VIEW.right, VIEW.bottom],
  ])
  .precision(0.5);
// The coarse outline is enough under the dots and keeps the page small.
const coast = geoPath(projection).digits(0)(feature(coarse, coarse.objects.land)) ?? "";

writeFileSync(
  new URL("../src/components/home/globe-data.ts", import.meta.url),
  `// SPDX-License-Identifier: MPL-2.0
// Generated by scripts/globe-data.ts from Natural Earth land (public domain, via world-atlas). Do not edit.

export const LAND_DOTS = "${dots.join("")}";

export const GRATICULE = "${graticule}";

export const COASTLINE = "${coast}";
`,
);
console.log(`${dots.length} land dots`);
